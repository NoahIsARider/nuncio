// Encode renders the config as deterministic TOML with short explanatory
// comments. It is used by init and discover.
func (c *Config) Encode() string {
	var b strings.Builder
	b.WriteString("# nuncio.toml — generated by `nuncio init`. Safe by construction:\n")
	b.WriteString("# dry_run = true, divergence is parked, every overwrite is snapshotted.\n")
	b.WriteString("# Secrets are references only (env:, file:, ssh:, keyring:).\n\n")
	fmt.Fprintf(&b, "version = %d\n", c.Version)

	b.WriteString("\n[state]\n")
	fmt.Fprintf(&b, "path = %s\n", quote(c.State.Path))
	fmt.Fprintf(&b, "cache = %s\n", quote(c.State.Cache))

	b.WriteString("\n[daemon]\n")
	fmt.Fprintf(&b, "listen = %s            # empty string disables the webhook listener entirely\n", quote(c.Daemon.Listen))
	fmt.Fprintf(&b, "interval = %s          # reconcile timer floor, per repo\n", quote(c.Daemon.Interval))
	fmt.Fprintf(&b, "concurrency = %d\n", c.Daemon.Concurrency)
	fmt.Fprintf(&b, "dry_run = %t              # turn off with: nuncio config set daemon.dry_run false\n", c.Daemon.DryRun)

	b.WriteString("\n[identity]\n")
	fmt.Fprintf(&b, "name = %s\n", quote(c.Identity.Name))
	fmt.Fprintf(&b, "email = %s\n", quote(c.Identity.Email))

	for _, name := range sortedKeys(c.Platforms) {
		p := c.Platforms[name]
		fmt.Fprintf(&b, "\n[platforms.%s]\n", quoteKey(name))
		fmt.Fprintf(&b, "kind = %s\n", quote(p.Kind))
		if p.API != "" {
			fmt.Fprintf(&b, "api = %s\n", quote(p.API))
		}
		if p.Git != "" {
			fmt.Fprintf(&b, "git = %s\n", quote(p.Git))
		}
		if p.Knot != "" {
			fmt.Fprintf(&b, "knot = %s\n", quote(p.Knot))
		}
		if p.Owner != "" {
			fmt.Fprintf(&b, "owner = %s\n", quote(p.Owner))
		}
		if p.Auth != "" {
			fmt.Fprintf(&b, "auth = %s\n", quote(p.Auth))
		}
		if p.Firehose != "" {
			fmt.Fprintf(&b, "firehose = %s\n", quote(p.Firehose))
		}
		if p.PreReceiveGate {
			fmt.Fprintf(&b, "pre_receive_gate = true\n")
		}
		if p.WebhookSecret != "" {
			fmt.Fprintf(&b, "webhook_secret = %s\n", quote(p.WebhookSecret))
		}
		if p.WebhookPublicKey != "" {
			fmt.Fprintf(&b, "webhook_public_key = %s\n", quote(p.WebhookPublicKey))
		}
	}

	for _, name := range sortedKeys(c.Policy) {
		pol := c.Policy[name]
		fmt.Fprintf(&b, "\n[policy.%s]\n", quoteKey(name))
		writeOptionalPolicy(&b, pol)
	}

	for _, slug := range sortedKeys(c.Repos) {
		r := c.Repos[slug]
		fmt.Fprintf(&b, "\n[repos.%s]\n", quoteKey(slug))
		if r.Policy != nil {
			fmt.Fprintf(&b, "policy = %s\n", quote(*r.Policy))
		}
		if r.Platforms != nil {
			fmt.Fprintf(&b, "platforms = %s\n", stringList(*r.Platforms))
		}
		if r.Authority != nil {
			fmt.Fprintf(&b, "authority = %s\n", quote(*r.Authority))
		}
		if r.OnDivergence != nil {
			fmt.Fprintf(&b, "on_divergence = %s\n", quote(*r.OnDivergence))
		}
		if r.OnDelete != nil {
			fmt.Fprintf(&b, "on_delete = %s\n", quote(*r.OnDelete))
		}
		if r.Snapshot != nil {
			fmt.Fprintf(&b, "snapshot = %t\n", *r.Snapshot)
		}
		if r.Verify != nil {
			fmt.Fprintf(&b, "verify = %t\n", *r.Verify)
		}
		if r.DefaultBranch != nil {
			fmt.Fprintf(&b, "default_branch = %s\n", quote(*r.DefaultBranch))
		}
		if len(r.Remote) > 0 {
			fmt.Fprintf(&b, "\n[repos.%s.remote]\n", quoteKey(slug))
			for _, plat := range sortedKeys(r.Remote) {
				fmt.Fprintf(&b, "%s = %s\n", quoteKey(plat), quote(r.Remote[plat]))
			}
		}
		for _, pattern := range capsSortPatterns(r.Refs) {
			rule := r.Refs[pattern]
			fmt.Fprintf(&b, "\n[repos.%s.refs.%s]\n", quoteKey(slug), quoteKey(pattern))
			if rule.Authority != nil {
				fmt.Fprintf(&b, "authority = %s\n", quote(*rule.Authority))
			}
			if rule.OnDivergence != nil {
				fmt.Fprintf(&b, "on_divergence = %s\n", quote(*rule.OnDivergence))
			}
			if rule.OnDelete != nil {
				fmt.Fprintf(&b, "on_delete = %s\n", quote(*rule.OnDelete))
			}
		}
	}

	for _, name := range sortedKeys(c.Groups) {
		g := c.Groups[name]
		fmt.Fprintf(&b, "\n[groups.%s]\n", quoteKey(name))
		fmt.Fprintf(&b, "policy = %s\n", quote(g.Policy))
		if len(g.Select) > 0 {
			parts := make([]string, 0, len(g.Select))
			for _, k := range sortedKeys(g.Select) {
				parts = append(parts, fmt.Sprintf("%s = %s", quoteKey(k), quote(g.Select[k])))
			}
			fmt.Fprintf(&b, "select = { %s }\n", strings.Join(parts, ", "))
		}
	}
	return b.String()
}

func writeOptionalPolicy(b *strings.Builder, p Policy) {
	if p.Platforms != nil {
		fmt.Fprintf(b, "platforms = %s\n", stringList(*p.Platforms))
	}
	if p.Authority != nil {
		fmt.Fprintf(b, "authority = %s\n", quote(*p.Authority))
	}
	if p.OnDivergence != nil {
		fmt.Fprintf(b, "on_divergence = %s\n", quote(*p.OnDivergence))
	}
	if p.OnDelete != nil {
		fmt.Fprintf(b, "on_delete = %s\n", quote(*p.OnDelete))
	}
	if p.Snapshot != nil {
		fmt.Fprintf(b, "snapshot = %t\n", *p.Snapshot)
	}
	if p.Verify != nil {
		fmt.Fprintf(b, "verify = %t\n", *p.Verify)
	}
	if p.DefaultBranch != nil {
		fmt.Fprintf(b, "default_branch = %s\n", quote(*p.DefaultBranch))
	}
}

// Save writes the config atomically enough for a CLI: write, then rename.
func Save(path string, c *Config) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(c.Encode()), 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

// UpdateDryRun flips daemon.dry_run in an existing file without rewriting
// comments or unrelated keys.
func UpdateDryRun(path string, value bool) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	lines := strings.Split(string(data), "\n")
	inDaemon := false
	replaced := false
	for i, line := range lines {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "[") {
			inDaemon = trimmed == "[daemon]"
			continue
		}
		if inDaemon && strings.HasPrefix(trimmed, "dry_run") {
			lines[i] = fmt.Sprintf("dry_run = %t              # turn off with: nuncio config set daemon.dry_run false", value)
			replaced = true
		}
	}
	if !replaced {
		// Insert into [daemon] if the block exists, otherwise append one.
		for i, line := range lines {
			if strings.TrimSpace(line) == "[daemon]" {
				insert := []string{fmt.Sprintf("dry_run = %t", value)}
				lines = append(lines[:i+1], append(insert, lines[i+1:]...)...)
				replaced = true
				break
			}
		}
		if !replaced {
			lines = append(lines, "", "[daemon]", fmt.Sprintf("dry_run = %t", value))
		}
	}
	return os.WriteFile(path, []byte(strings.Join(lines, "\n")), 0o644)
}

func capsSortPatterns(refs map[string]RefRule) []string {
	patterns := make([]string, 0, len(refs))
	for p := range refs {
		patterns = append(patterns, p)
	}
	sort.SliceStable(patterns, func(i, j int) bool {
		si, sj := specificity(patterns[i]), specificity(patterns[j])
		if si != sj {
			return si > sj
		}
		return patterns[i] < patterns[j]
	})
	return patterns
}

func specificity(pattern string) int {
	literal := 0
	for i := 0; i < len(pattern); i++ {
		if pattern[i] != '*' {
			literal++
		}
	}
	return literal
}

func quote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if r < 0x20 {
				b.WriteString(`\u`)
				b.WriteString(fmt.Sprintf("%04x", r))
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

func quoteKey(s string) string {
	if s == "" {
		return `""`
	}
	for _, r := range s {
		if !(r == '-' || r == '_' ||
			(r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9')) {
			return quote(s)
		}
	}
	return s
}

func stringList(values []string) string {
	parts := make([]string, len(values))
	for i, v := range values {
		parts[i] = quote(v)
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

// FormatByteSize is a tiny helper used by doctor output.
func FormatByteSize(n int64) string {
	const unit = 1024
	if n < unit {
		return strconv.FormatInt(n, 10) + " B"
	}
	div, exp := int64(unit), 0
	for m := n / unit; m >= unit; m /= unit {
		div *= unit
		exp++
	}
	return fmt.Sprintf("%.1f %ciB", float64(n)/float64(div), "KMGTPE"[exp])
}
